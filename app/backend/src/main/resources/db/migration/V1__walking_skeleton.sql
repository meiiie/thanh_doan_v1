create table campaign (
  id varchar(80) primary key,
  name varchar(240) not null,
  phase varchar(40) not null,
  scorecard_version_id varchar(80) not null,
  version integer not null default 0
);

create table source_document (
  id varchar(80) primary key,
  file_name varchar(500) not null,
  sha256 varchar(64) not null unique,
  received_scope varchar(1000) not null,
  imported_at timestamp with time zone not null
);

create table scorecard_version (
  id varchar(80) primary key,
  campaign_id varchar(80) not null references campaign(id),
  title varchar(500) not null,
  audience varchar(1000) not null,
  status varchar(40) not null,
  source_document_id varchar(80) not null references source_document(id),
  core_maximum decimal(8,2) not null,
  bonus_raw_maximum decimal(8,2) not null,
  bonus_cap decimal(8,2) not null,
  version integer not null default 0
);

create table scorecard_group (
  id varchar(80) primary key,
  scorecard_version_id varchar(80) not null references scorecard_version(id),
  code varchar(40) not null,
  title varchar(1000) not null,
  section varchar(20) not null,
  display_order integer not null,
  unique (scorecard_version_id, code)
);

create table scorecard_line (
  id varchar(80) primary key,
  scorecard_version_id varchar(80) not null references scorecard_version(id),
  group_id varchar(80) not null references scorecard_group(id),
  code varchar(40) not null,
  title varchar(1000) not null,
  requirement varchar(8000) not null,
  evidence_hint varchar(4000) not null,
  report_template varchar(4000) not null,
  evidence_policy varchar(30) not null,
  maximum_score decimal(8,2) not null,
  source_sheet varchar(120) not null,
  source_row integer not null,
  display_order integer not null,
  unique (scorecard_version_id, code)
);

create table unit_group (
  code varchar(40) primary key,
  name varchar(240) not null,
  documented_unit_count integer not null,
  source_reference varchar(500) not null
);

create table app_account (
  id varchar(80) primary key,
  username varchar(120) not null unique,
  display_name varchar(240) not null,
  password_hash varchar(100) not null,
  role varchar(40) not null,
  organization_id varchar(80),
  team_id varchar(80),
  enabled boolean not null default true,
  password_change_required boolean not null default true,
  created_at timestamp with time zone not null,
  created_by varchar(80)
);

create table account_campaign_scope (
  account_id varchar(80) not null references app_account(id),
  campaign_id varchar(80) not null references campaign(id),
  primary key (account_id, campaign_id)
);

create table account_capability (
  account_id varchar(80) not null references app_account(id),
  capability varchar(100) not null,
  primary key (account_id, capability)
);

create table authentication_event (
  id bigint generated by default as identity primary key,
  occurred_at timestamp with time zone not null,
  account_id varchar(80),
  username varchar(120) not null,
  event_type varchar(40) not null,
  outcome varchar(20) not null
);

create table submission (
  id varchar(80) primary key,
  campaign_id varchar(80) not null references campaign(id),
  organization_id varchar(80) not null,
  line_id varchar(80) not null references scorecard_line(id),
  status varchar(40) not null,
  self_score decimal(8,2) not null,
  evidence_url varchar(2000) not null,
  summary varchar(4000) not null,
  revision integer not null default 0,
  version integer not null default 0,
  unique (campaign_id, organization_id, line_id)
);

create table submission_revision (
  id varchar(100) primary key,
  submission_id varchar(80) not null references submission(id),
  revision integer not null,
  self_score decimal(8,2) not null,
  evidence_url varchar(2000) not null,
  summary varchar(4000) not null,
  submitted_by varchar(80) not null,
  submitted_at timestamp with time zone not null,
  unique (submission_id, revision)
);

create table review_case (
  id varchar(80) primary key,
  submission_id varchar(80) not null references submission(id),
  line_id varchar(80) not null references scorecard_line(id),
  team_id varchar(80) not null,
  reviewer_id varchar(80) not null,
  round1_status varchar(40) not null,
  round2_status varchar(40) not null,
  version integer not null default 0,
  unique (submission_id, line_id)
);

create table review_decision (
  id varchar(100) primary key,
  review_case_id varchar(80) not null references review_case(id),
  round_number integer not null,
  revision integer not null,
  awarded_score decimal(8,2) not null,
  reason varchar(4000),
  evidence_checked boolean not null,
  decided_by varchar(80) not null,
  decided_at timestamp with time zone not null,
  unique (review_case_id, round_number, revision)
);

create table explanation_revision (
  id varchar(100) primary key,
  review_case_id varchar(80) not null references review_case(id),
  revision integer not null,
  body varchar(4000) not null,
  evidence_url varchar(2000),
  submitted_by varchar(80) not null,
  submitted_at timestamp with time zone not null,
  unique (review_case_id, revision)
);

create table final_result (
  id varchar(100) primary key,
  campaign_id varchar(80) not null references campaign(id),
  result_version integer not null,
  status varchar(40) not null,
  total_score decimal(8,2) not null,
  checksum varchar(128) not null,
  prepared_by varchar(80) not null,
  prepared_at timestamp with time zone not null,
  approved_by varchar(80),
  approved_at timestamp with time zone,
  published_by varchar(80),
  published_at timestamp with time zone,
  version integer not null default 0,
  unique (campaign_id, result_version)
);

create table audit_record (
  id bigint generated by default as identity primary key,
  occurred_at timestamp with time zone not null,
  actor_id varchar(80) not null,
  action varchar(100) not null,
  aggregate_type varchar(80) not null,
  aggregate_id varchar(100) not null,
  from_state varchar(80),
  to_state varchar(80) not null,
  reason varchar(4000),
  correlation_id varchar(100) not null,
  aggregate_version integer not null
);

create table idempotency_record (
  actor_id varchar(80) not null,
  command_name varchar(100) not null,
  idempotency_key varchar(120) not null,
  request_fingerprint varchar(128) not null,
  created_at timestamp with time zone not null,
  primary key (actor_id, command_name, idempotency_key)
);

create index idx_audit_aggregate on audit_record (aggregate_type, aggregate_id, id);
create index idx_review_decision_case on review_decision (review_case_id, round_number, revision);
create index idx_scorecard_line_group on scorecard_line (group_id, display_order);
create index idx_authentication_event_account on authentication_event (account_id, occurred_at);
